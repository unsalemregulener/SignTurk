def restore_turkish(word: str) -> str:
    """Turkish spelling of a sign gloss; unknown words are returned unchanged."""
    if not isinstance(word, str):
        return word
    key = word.strip().lower()
    return SIGN_GLOSS_TURKISH.get(key, word.strip())


def restore_turkish_words(words: Iterable[str]) -> List[str]:
    return [restore_turkish(w) for w in words]
